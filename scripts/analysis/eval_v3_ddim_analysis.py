"""DDIM-steps analysis v3 — interior air and porosity error vs step count.

Joins the DDIM probe set generated by ``eval_v3_ddim_probe.py`` to the two
measurements made on it elsewhere:

* ``runs/campaigns/05-eval-v3-fixed-decode/air_audit/per_volume.csv`` — unmasked air at the calibrated
  absolute threshold T_abs = 182, split interior vs 32-voxel edge shell.
* ``runs/campaigns/05-eval-v3-fixed-decode/onlypores/per_volume.csv`` — onlypores porosity (subject to
  the 192³ global-Otsu caveat documented there).

Question, restated on correctly-decoded volumes: does more DDIM sampling
reduce interior air, and does it move delivered porosity toward the target?

Outputs -> ``runs/campaigns/05-eval-v3-fixed-decode/ddim/``: results.json, findings.md, figures.

Usage:
    python scripts/analysis/eval_v3_ddim_analysis.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import savefig, set_style, write_findings, write_json, plt  # noqa: E402
from _eval_v3 import (  # noqa: E402
    DDIM_ARM, DDIM_S_POR, DDIM_SEEDS, DDIM_STEP_COUNTS, DDIM_TARGET,
    DDIM_VOL_ROOT, ROOT, load_calibration,
)

OUT_DIR = ROOT / "ddim"
AIR_CSV = ROOT / "air_audit" / "per_volume.csv"
OP_CSV = ROOT / "onlypores" / "per_volume.csv"

SEED_COLORS = {101: "#1b6ca8", 202: "#c2571a"}


def _wall(v) -> str:
    return "n/a" if v is None else f"{v:.0f}"


def monotone_reduction(rows: list[dict], key: str) -> tuple[bool, str]:
    """Same criterion as ldm06_probe.py: non-increasing in the step count
    within a 2 %-of-DDIM-50 tolerance, AND a >=20 % relative drop."""
    ok, notes = True, []
    for seed in DDIM_SEEDS:
        ys = [r[key] for r in sorted((r for r in rows if r["seed"] == seed),
                                     key=lambda r: r["ddim_steps"])]
        if not ys:
            continue
        tol = max(0.02 * ys[0], 5e-4)
        mono = all(b <= a + tol for a, b in zip(ys, ys[1:]))
        drop = (ys[0] - min(ys)) / ys[0] if ys[0] > 0 else 0.0
        ok &= mono and drop >= 0.20
        notes.append(f"seed {seed}: {['%.4f' % y for y in ys]} mono={mono} "
                     f"rel_drop={drop:.2f}")
    return ok, "; ".join(notes)


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    set_style()
    cal = load_calibration()

    air = pd.read_csv(AIR_CSV)
    air = air[air.experiment == "ddim_probe"]
    if not len(air):
        raise SystemExit(f"no ddim_probe rows in {AIR_CSV}")
    op = pd.read_csv(OP_CSV)
    op = op[op.experiment == "ddim_probe"][
        ["name", "onlypores_porosity_sample", "onlypores_porosity_total",
         "sample_mask_fraction", "dice_mask_vs_onlypores"]]
    df = air.merge(op, on="name", how="left")

    walls = {d.name: json.loads((d / "stats.json").read_text())
             for d in sorted(DDIM_VOL_ROOT.iterdir())
             if (d / "stats.json").exists()}

    rows = []
    for _, r in df.iterrows():
        st = walls.get(r["name"], {})
        steps = int(st.get("ddim_steps", r.get("ddim_steps")))
        seed = int(st.get("seed", r.get("seed")))
        delivered = float(r["mask_porosity"])
        rows.append({
            "name": r["name"], "ddim_steps": steps, "seed": seed,
            "mask_porosity": delivered,
            "mask_abs_error": abs(delivered - DDIM_TARGET),
            "onlypores_porosity_sample": float(r["onlypores_porosity_sample"]),
            "onlypores_abs_error": abs(float(r["onlypores_porosity_sample"])
                                       - DDIM_TARGET),
            "sample_mask_fraction": float(r["sample_mask_fraction"]),
            "detected_air_abs": float(r["detected_air_abs"]),
            "unmasked_air_abs": float(r["unmasked_air_abs"]),
            "unmasked_interior_local_abs": float(r["unmasked_interior_local_abs"]),
            "unmasked_edge_local_abs": float(r["unmasked_edge_local_abs"]),
            "mask_capture_of_detected": float(r["mask_capture_of_detected"]),
            "grey_range": [int(r["raw_min_u8"]), int(r["raw_max_u8"])],
            "wall_s": st.get("wall_s"),
        })
    rows.sort(key=lambda r: (r["ddim_steps"], r["seed"]))

    per_step = []
    for steps in DDIM_STEP_COUNTS:
        s = [r for r in rows if r["ddim_steps"] == steps]
        if not s:
            continue
        per_step.append({
            "ddim_steps": steps, "n": len(s),
            "mask_porosity_mean": float(np.mean([r["mask_porosity"] for r in s])),
            "mask_abs_error_mean": float(np.mean([r["mask_abs_error"] for r in s])),
            "onlypores_porosity_mean": float(np.mean(
                [r["onlypores_porosity_sample"] for r in s])),
            "onlypores_abs_error_mean": float(np.mean(
                [r["onlypores_abs_error"] for r in s])),
            "detected_air_mean": float(np.mean([r["detected_air_abs"] for r in s])),
            "unmasked_air_mean": float(np.mean([r["unmasked_air_abs"] for r in s])),
            "interior_air_mean": float(np.mean(
                [r["unmasked_interior_local_abs"] for r in s])),
            "edge_air_mean": float(np.mean([r["unmasked_edge_local_abs"] for r in s])),
            "sample_mask_fraction_mean": float(np.mean(
                [r["sample_mask_fraction"] for r in s])),
            "wall_s_mean": (float(np.mean([r["wall_s"] for r in s]))
                            if all(r["wall_s"] is not None for r in s) else None),
        })

    mono_ok, mono_note = monotone_reduction(rows, "unmasked_interior_local_abs")

    results = {
        "campaign": "eval v3 — DDIM step sweep on correctly-decoded volumes",
        "protocol": {"arm": DDIM_ARM, "mode": "joint",
                     "conditioning_semantics": "specimen",
                     "s_por": DDIM_S_POR, "target": DDIM_TARGET,
                     "ddim_steps": DDIM_STEP_COUNTS, "seeds": DDIM_SEEDS,
                     "volume_vox": 192,
                     "field": "coherent (T-E sampler + T-D corr lengths)"},
        "detector": {"T_abs": cal["t_abs"], "real_dice": cal["dice"],
                     "min_cc_voxels": cal["min_cc_voxels"],
                     "edge_shell_vox": cal["edge_shell_vox"]},
        "real_false_positive_baseline": cal["real_false_positive_baseline"],
        "per_step": per_step,
        "volumes": rows,
        "monotone_interior_air_reduction": mono_ok,
        "monotone_note": mono_note,
        "figures": [],
    }

    figs = []
    fig, axes = plt.subplots(1, 3, figsize=(13.2, 4.2), constrained_layout=True)
    ax = axes[0]
    for seed in DDIM_SEEDS:
        s = [r for r in rows if r["seed"] == seed]
        ax.plot([r["ddim_steps"] for r in s],
                [r["unmasked_interior_local_abs"] for r in s], "o-",
                color=SEED_COLORS[seed], label=f"interior, seed {seed}")
        ax.plot([r["ddim_steps"] for r in s],
                [r["unmasked_edge_local_abs"] for r in s], "s--",
                color=SEED_COLORS[seed], alpha=0.5, label=f"edge, seed {seed}")
    ax.axhline(cal["real_false_positive_baseline"]["mean"], color="0.35",
               ls=":", lw=1.2, label="real false-positive floor")
    ax.set_xticks(DDIM_STEP_COUNTS)
    ax.set_xlabel("DDIM steps")
    ax.set_ylabel("unmasked air (local fraction)")
    ax.set_title(f"Unmasked air, T_abs = {cal['t_abs']}")
    ax.legend(fontsize=7.5)

    ax = axes[1]
    for seed in DDIM_SEEDS:
        s = [r for r in rows if r["seed"] == seed]
        ax.plot([r["ddim_steps"] for r in s],
                [r["mask_porosity"] for r in s], "o-",
                color=SEED_COLORS[seed], label=f"mask φ, seed {seed}")
        ax.plot([r["ddim_steps"] for r in s],
                [r["onlypores_porosity_sample"] for r in s], "^--",
                color=SEED_COLORS[seed], alpha=0.6,
                label=f"onlypores φ, seed {seed}")
    ax.axhline(DDIM_TARGET, color="0.35", ls=":", lw=1.2,
               label=f"target {DDIM_TARGET:g}")
    ax.set_xticks(DDIM_STEP_COUNTS)
    ax.set_xlabel("DDIM steps")
    ax.set_ylabel("delivered porosity")
    ax.set_title("Delivered porosity vs steps")
    ax.legend(fontsize=7.5)

    ax = axes[2]
    ax.plot([p["ddim_steps"] for p in per_step],
            [p["mask_abs_error_mean"] for p in per_step], "o-",
            color="#1b6ca8", label="|mask φ − target|")
    ax.plot([p["ddim_steps"] for p in per_step],
            [p["onlypores_abs_error_mean"] for p in per_step], "^--",
            color="#c2571a", label="|onlypores φ − target|")
    ax.set_xticks(DDIM_STEP_COUNTS)
    ax.set_xlabel("DDIM steps")
    ax.set_ylabel("mean absolute porosity error")
    ax.set_title("Porosity error vs steps")
    ax.legend(fontsize=7.5)

    fig.suptitle(f"DDIM step sweep v3 — {DDIM_ARM}, s_por {DDIM_S_POR}, "
                 f"target {DDIM_TARGET:g}, 192³, correct decode")
    figs += savefig(fig, OUT_DIR, "ddimv3_fig1_air_and_porosity_vs_steps")
    results["figures"] = figs
    p_json = write_json(results, OUT_DIR)

    L = ["# DDIM step sweep — eval v3 (correct decode)", "",
         f"{len(rows)} volumes, {DDIM_ARM} (joint + specimen semantics), "
         f"s_por {DDIM_S_POR}, target φ {DDIM_TARGET:g}, 192³, seeds "
         f"{DDIM_SEEDS}. Air measured with the real-calibrated absolute "
         f"threshold T_abs = {cal['t_abs']} (Dice {cal['dice']:.3f} on real "
         f"volumes), components < {cal['min_cc_voxels']} voxels dropped, "
         f"interior/edge split at a {cal['edge_shell_vox']}-voxel shell.", "",
         "| steps | mask φ | onlypores φ | \\|mask err\\| | detected air "
         "| unmasked air | interior | edge | sample-mask frac | wall (s) |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for p in per_step:
        L.append(f"| {p['ddim_steps']} | {p['mask_porosity_mean']:.4f} "
                 f"| {p['onlypores_porosity_mean']:.4f} "
                 f"| {p['mask_abs_error_mean']:.4f} "
                 f"| {p['detected_air_mean']:.4f} "
                 f"| {p['unmasked_air_mean']:.4f} "
                 f"| {p['interior_air_mean']:.4f} | {p['edge_air_mean']:.4f} "
                 f"| {p['sample_mask_fraction_mean']:.3f} "
                 f"| {_wall(p['wall_s_mean'])} |")
    L += ["",
          f"Monotone interior-air reduction (ldm06 criterion: non-increasing "
          f"within 2 % of the DDIM-50 value AND ≥20 % relative drop): "
          f"**{'YES' if mono_ok else 'NO'}** — {mono_note}", "",
          f"Real-volume false-positive floor for this detector: "
          f"{cal['real_false_positive_baseline']['mean']:.4f} "
          f"(max {cal['real_false_positive_baseline']['max']:.4f}).", "",
          "onlypores φ carries the 192³ global-Otsu caveat documented in "
          "`runs/campaigns/05-eval-v3-fixed-decode/onlypores/findings.md`; use it for the trend across "
          "step counts, not as an absolute porosity.", ""]
    p_md = write_findings("\n".join(L), OUT_DIR)
    print("Wrote", p_json, p_md, *figs, sep="\n  ", flush=True)


if __name__ == "__main__":
    main()
